import type { LogicalType } from '@/domain/logical-type.ts';
import type { EntityId } from '@/shared/ids/entity-id.ts';

export type DatasetSourceKind = 'csv' | 'json';

export interface DatasetSource {
  kind: DatasetSourceKind;
  /** Display-only filename as supplied by the user. Never used to build SQL identifiers. */
  fileName: string;
  byteSize: number;
  importedAt: string;
}

export interface Column {
  id: EntityId;
  /** Human-facing label, shown in the UI and exposed to agents. */
  name: string;
  /** Identifier inside the DuckDB relation. The query compiler resolves and quotes it. */
  physicalName: string;
  databaseType: string;
  logicalType: LogicalType;
  nullable: boolean;
}

export type DatasetImportStatus = 'loading' | 'ready' | 'error';

export interface Dataset {
  id: EntityId;
  name: string;
  /**
   * Internal DuckDB relation name, generated by the application.
   *
   * Security invariant. This is never user- or agent-supplied SQL and never comes from the
   * uploaded filename. A file called `Q4 sales; DROP TABLE...csv` still maps to an opaque
   * generated relation.
   */
  relationId: string;
  source: DatasetSource;
  rowCount: number | null;
  columns: Column[];
  revision: number;
  importStatus: DatasetImportStatus;
}
